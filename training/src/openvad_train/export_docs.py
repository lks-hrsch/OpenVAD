"""Write numbers and figures from the parity fixture into the thesis tree."""

import sys
from pathlib import Path

from safetensors.numpy import load_file


FIXTURE = Path(__file__).parents[3] / "inferencing/fixtures/smoke/linear.safetensors"
HEADER = "% Generated by openvad_train.export_docs. Do not edit.\n"


def main(argv: list[str] | None = None) -> None:
    (docs,) = sys.argv[1:] if argv is None else argv
    expected = load_file(FIXTURE)["expected"].ravel().tolist()
    figure = [r"\begin{tikzpicture}[y=0.5cm]", rf"\draw (-0.2,0) -- ({len(expected)},0);"]
    figure += [rf"\fill ({i},0) rectangle ({i + 0.6},{v:g});" for i, v in enumerate(expected)]
    figure += [r"\end{tikzpicture}"]
    docs_dir = Path(docs)
    write(
        docs_dir / "shared/generated/numbers.tex",
        rf"\newcommand{{\SmokeExpectedFirst}}{{{expected[0]:g}}}" + "\n",
    )
    write(docs_dir / "images/generated/smoke-expected.tex", "\n".join(figure) + "\n")


def write(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + body)


if __name__ == "__main__":
    main()
