"""Design the half-band filter of the one OpenVAD resampler (ADR 0009).

`just design-resampler` rewrites `resample_coefficients.rs` from `coefficients()`.
"""

from pathlib import Path

import numpy as np
from scipy.signal import remez


TAPS = 71  # 63 reaches -69.6 dB and 67 -67.3 dB once DC is exactly 1; length must be 4k - 1
FS = 16000
EDGE = 3500  # passband edge; the half-band stopband edge is FS / 2 - EDGE, symmetric about 4 kHz
OUTPUT = Path(__file__).parents[3] / "inferencing/openvad-core/src/resample_coefficients.rs"


def coefficients() -> np.ndarray:
    """Return the `TAPS` half-band taps as float32, with unity DC gain."""
    c = remez(TAPS, [0, EDGE, FS // 2 - EDGE, FS // 2], [1, 0], fs=FS, maxiter=200)
    centre = TAPS // 2
    distance = np.abs(np.arange(TAPS) - centre)
    c = (c + c[::-1]) / 2
    c[(distance % 2 == 0) & (distance > 0)] = 0.0
    c[centre] = 0.5
    odd = distance % 2 == 1
    c[odd] *= 0.5 / c[odd].sum()
    return c.astype(np.float32)


def render() -> str:
    # `repr` of a float32 is the shortest decimal that parses back to the same f32.
    body = "".join(f"    {v!s},\n" for v in coefficients())
    return (
        "// Copyright (c) 2026 Lukas Hirsch\n"
        "// This Source Code Form is subject to the terms of the Mozilla Public\n"
        "// License, v. 2.0. If a copy of the MPL was not distributed with this\n"
        "// file, You can obtain one at https://mozilla.org/MPL/2.0/.\n"
        "\n"
        "// Generated by `just design-resampler` from openvad_train.design_resampler. Do not edit.\n"
        "\n"
        "/// Half-band taps, linear phase, unity DC gain.\n"
        "#[rustfmt::skip]\n"
        "#[allow(clippy::unreadable_literal)]\n"
        f"pub const HALF_BAND: [f32; {TAPS}] = [\n{body}];\n"
    )


def main() -> None:
    OUTPUT.write_text(render())


if __name__ == "__main__":
    main()
